/**
 * Regenerate src/util/harden-soul-lines.ts from the installed generator.
 *
 *   npm run gen:harden-soul-lines
 *
 * Run after upgrading hackmyagent; harden-soul-lines.test.ts fails until the
 * file matches what the generator writes.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { deriveHardenSoulLines } from './harden-soul-template-lines.js';
import { soulLineDigest } from '../src/util/soul-line.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'src', 'util', 'harden-soul-lines.ts');

async function main(): Promise<void> {
  const lines = await deriveHardenSoulLines();
  const digests = [...new Set(lines.map(soulLineDigest))].sort();
  const body = [
    '/**',
    ' * SHA-256 digests (soulLineDigest in soul-line.ts) of every line',
    ' * `harden-soul` (hackmyagent SoulScanner.hardenSoul) can write.',
    ' * GENERATED by scripts/gen-harden-soul-lines.ts from the generator\'s own',
    ' * templates; do not edit by hand. harden-soul-lines.test.ts fails when',
    ' * this differs from what the generator writes.',
    ' */',
    'export const HARDEN_SOUL_LINE_DIGESTS: readonly string[] = [',
    ...digests.map(d => `  '${d}',`),
    '];',
    '',
  ].join('\n');
  fs.writeFileSync(out, body, 'utf-8');
  process.stdout.write(`wrote ${digests.length} line digests to ${path.relative(process.cwd(), out)}\n`);
}

main().catch((err: unknown) => {
  process.stderr.write(`${err instanceof Error ? err.message : String(err)}\n`);
  process.exit(1);
});
